async page => {
  const assert=(ok,message)=>{if(!ok)throw Error(message);};
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.locator('.image-card').first().waitFor();
  assert(await page.locator('.image-card').count()===10,'10 cards');
  assert(await page.locator('#card-grid .verse').count()===10,'10 ayahs');
  const source=await page.evaluate(async()=> (await (await fetch('../../data/ayahs.json')).json()).surahs['74']);
  const displayed=await page.locator('#card-grid .arabic').evaluateAll(elements=>elements.map(el=>el.querySelector('.basmala')?[el.querySelector('.basmala').textContent,el.querySelector('.ayah-body').textContent].join(' '):el.textContent));
  assert(displayed.every((text,index)=>text===source[index].text),'verbatim Tanzil rendering');
  const photos=await page.locator('#card-grid .poster-photo').evaluateAll(async images=>{await Promise.all(images.map(image=>{image.loading='eager';return image.decode();}));return images.map(image=>({src:image.src,width:image.naturalWidth,height:image.naturalHeight}));});
  assert(new Set(photos.map(image=>image.src)).size===10,'10 distinct image URLs');
  assert(photos.every(image=>image.width>=1000&&image.height>=700),'10 decoded high-resolution images');
  await page.evaluate(()=>document.fonts.ready);
  const first=page.locator('.image-card[data-card="0"]');
  await first.scrollIntoViewIfNeeded();
  await page.screenshot({path:'output/playwright/muddassir10-desktop.png'});
  await first.locator('[data-action="open"]').click();
  for(let i=1;i<=10;i++){
    assert((await page.locator('#modal-position').textContent())===`${i} / 10`,'gallery ayah '+i);
    assert(await page.locator('#modal-poster .verse').count()===1,'one ayah per poster');
    await page.getByRole('button',{name:'Следующая →',exact:true}).click();
  }
  assert((await page.locator('#modal-position').textContent())==='1 / 10','gallery wraps');
  await page.keyboard.press('ArrowLeft');
  assert((await page.locator('#modal-position').textContent())==='10 / 10','keyboard previous');
  await page.keyboard.press('Escape');
  await first.locator('summary').click();
  await first.getByRole('button',{name:'Повторить аят 1',exact:true}).click();
  let stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('quran-hifz:v1')));
  assert(stored.ayahs['74:1'].reads===1&&!stored.ayahs['74:2']?.reads,'count affects only ayah1');
  assert(!stored.ayahs['74:1'].learned,'read does not auto verify');
  await first.getByRole('button',{name:'✓ Проверено',exact:true}).click();
  assert((await page.locator('#memory-total').textContent()).startsWith('0 /'),'verification gate');
  await first.getByRole('checkbox').check();
  await first.getByRole('button',{name:'✓ Проверено',exact:true}).click();
  assert((await page.locator('#memory-total').textContent()).startsWith('1 /'),'one verified ayah');
  await page.reload();await page.locator('.image-card').first().waitFor();
  assert((await page.locator('#memory-total').textContent()).startsWith('1 /'),'progress survives reload');
  await page.getByRole('checkbox',{name:'Читать наизусть',exact:true}).check();
  assert(await page.locator('#card-grid .arabic[aria-hidden="true"]').count()===10,'recall hides all10');
  await first.locator('[data-action="open"]').click();
  assert(await page.locator('#modal-poster .arabic[aria-hidden="true"]').count()===1,'modal respects recall');
  await page.keyboard.press('Escape');
  await page.getByRole('checkbox',{name:'Читать наизусть',exact:true}).uncheck();
  const contact=await page.context().newPage();
  await contact.setViewportSize({width:1280,height:1240});
  await contact.setContent(`<html><body style="margin:0;padding:12px;background:#0d1b3e;color:#eee;font:18px Arial;display:grid;grid-template-columns:repeat(4,1fr);gap:12px">${photos.map((image,i)=>`<div><div>74:${i+1}</div><img src="${image.src}" style="width:100%;height:105px;object-fit:contain"></div>`).join('')}</body></html>`);
  await contact.locator('img').evaluateAll(images=>Promise.all(images.map(image=>image.decode())));
  await contact.screenshot({path:'output/playwright/muddassir10-contact.png',fullPage:true});await contact.close();
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no mobile overflow');
  await first.scrollIntoViewIfNeeded();
  await first.locator('.poster-sheet').screenshot({path:'output/playwright/muddassir10-card01-mobile.png'});
  await page.evaluate(async()=>{await navigator.serviceWorker.ready;});
  await page.context().setOffline(true);await page.reload();
  await page.locator('.image-card').first().waitFor();
  assert(await page.locator('.image-card').count()===10,'offline all10');
  await page.locator('#card-grid .poster-photo').evaluateAll(images=>Promise.all(images.map(image=>{image.loading='eager';return image.decode();})));
  await page.context().setOffline(false);
  await page.getByRole('link',{name:'Тренажёр хифза',exact:true}).click();
  await page.getByRole('link',{name:'Аяты 1–10: тафсир и картинки',exact:true}).waitFor();
  assert((await page.locator('#verified-status').textContent()).includes('Проверено'),'shared verified progress');
  assert(await page.locator('#read-count').textContent()==='1','shared counter');
  assert(errors.length===0,errors.join('; '));
  return 'PASS: 10 unique decoded images, exact Arabic, all10 modal cards, recall, isolated counters and verification, persisted shared progress, mobile, offline images.';
}
