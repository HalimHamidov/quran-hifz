async page => {
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.reload();
  await page.locator('#read-count').waitFor();
  await page.getByRole('button',{name:'+1 повторение',exact:true}).click();
  assert(await page.locator('#read-count').textContent()==='1','counter increment');
  await page.getByRole('button',{name:'✓ Проверено',exact:true}).click();
  assert(await page.locator('#verified-status').textContent()==='Ещё не проверено','unchecked verification gate');
  await page.getByRole('checkbox',{name:'Прочитал(а) без подсказки и проверил(а) таджвид'}).check();
  await page.getByRole('button',{name:'✓ Проверено',exact:true}).click();
  await page.reload();await page.locator('#read-count').waitFor();
  assert(await page.locator('#read-count').textContent()==='1','read count persists after reload');
  assert((await page.locator('#verified-status').textContent()).includes('Проверено'),'learned status persists');
  await page.getByRole('button',{name:'Читать наизусть',exact:true}).click();
  assert(await page.locator('#verse-text').getAttribute('aria-hidden')==='true','recall hides Arabic');
  await page.getByRole('link',{name:'Следующий аят →',exact:true}).click();
  await page.locator('#read-count').waitFor();
  assert(await page.locator('#read-count').textContent()==='0','new verse independent count');
  assert(!(await page.getByRole('button',{name:'+1 соединение',exact:true}).isEnabled()),'unlearned verse blocks join');
  await page.getByRole('checkbox',{name:'Прочитал(а) без подсказки и проверил(а) таджвид'}).check();
  await page.getByRole('button',{name:'✓ Проверено',exact:true}).click();
  await page.getByRole('button',{name:'+1 соединение',exact:true}).click();
  assert(await page.locator('#join-count').textContent()==='1','join increment');
  await page.getByRole('button',{name:'История и смыслы',exact:true}).click();
  assert(await page.locator('[data-action="visual"]').count()===5,'five semantic visual blocks');
  await page.locator('[data-action="visual"][data-index="0"]').click();
  assert(await page.locator('#visual-dialog').isVisible(),'fullscreen visual opens');
  await page.getByRole('button',{name:'Далее →',exact:true}).click();
  assert((await page.locator('#visual-title').textContent()).includes('11–25'),'fullscreen next image');
  await page.keyboard.press('Escape');
  assert(!(await page.locator('#visual-dialog').isVisible()),'Escape closes modal');
  await page.getByRole('link',{name:'Настройки и резервная копия',exact:true}).click();
  await page.getByRole('checkbox',{name:'Приостановить только новое заучивание'}).check();
  await page.getByRole('link',{name:'Муроджаа',exact:true}).click();
  assert(await page.getByRole('heading',{name:'Постоянное повторение',exact:true}).isVisible(),'review remains active when paused');
  assert(await page.getByRole('button',{name:'✓ Прочитано без ошибки',exact:true}).count()>0,'review tasks exist');
  await page.getByRole('button',{name:'✓ Прочитано без ошибки',exact:true}).first().click();
  await page.getByRole('link',{name:'Суры',exact:true}).click();
  await page.locator('#surah-results').waitFor();
  assert(await page.locator('#surah-results .surah-row').count()===114,'114 catalog entries');
  await page.getByRole('searchbox',{name:'Найти суру'}).fill('74');
  assert(await page.locator('#surah-results .surah-row').count()===1,'search filters catalog');
  await page.locator('#surah-results .surah-row').click();
  assert(!(await page.getByRole('button',{name:'+1 повторение',exact:true}).isEnabled()),'pause disables new reads');
  await page.getByRole('button',{name:'Все аяты',exact:true}).click();
  await page.locator('.ayah-list').waitFor();
  assert(await page.locator('.ayah-list article').count()===56,'all 56 Muddaththir ayahs rendered');
  await page.getByRole('link',{name:'История',exact:true}).click();
  await page.locator('.year-strip').waitFor();
  assert(await page.locator('[data-action="year"]').count()===23,'23 timeline years');
  await page.locator('[data-year="13"]').click();
  assert(await page.getByRole('heading',{name:'Хиджра: Мекка → Медина',exact:true}).isVisible(),'Hijra source-backed event');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('link',{name:'Мой путь',exact:true}).click();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'mobile home no overflow');
  await page.screenshot({path:'output/playwright/home-mobile.png',fullPage:true});
  await page.goto('http://127.0.0.1:4175/quran-hifz/#surah/74/56');
  await page.locator('#verse-text').waitFor();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'mobile reader no overflow');
  await page.screenshot({path:'output/playwright/reader-mobile.png',fullPage:true});
  await page.context().setOffline(true);
  await page.reload();await page.locator('#verse-text').waitFor();
  assert((await page.title()).includes('56'),'offline reload works');
  await page.context().setOffline(false);
  assert(errors.length===0,`console errors: ${errors.join('; ')}`);
  console.log('PASS: counters, verification, persistence, joins, fullscreen, paused review, 114 surahs, 56 ayahs, timeline, 390px responsive layout, offline reload; no JS errors.');
}
