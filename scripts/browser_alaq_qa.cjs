async page => {
  const assert=(ok,message)=>{if(!ok)throw Error(message);};
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.locator('.image-card').first().waitFor();
  assert(await page.locator('.image-card').count()===10,'10 cards');
  assert(await page.locator('.prayer-row').count()===5,'5 prayer rows');
  assert(await page.locator('.verse').count()===19,'19 ayahs');
  const source=await page.evaluate(async()=> (await (await fetch('../../data/ayahs.json')).json()).surahs['96']);
  const displayed=await page.locator('#card-grid .arabic').allTextContents();
  assert(displayed.every((text,index)=>text===source[index].text),'verbatim Tanzil rendering');
  await page.evaluate(()=>document.fonts.ready);
  await page.screenshot({path:'output/playwright/alaq-desktop.png'});
  await page.getByRole('button',{name:'Открыть карточку 1: Читай. Помни о сотворении',exact:true}).click();
  assert(await page.locator('#poster-modal').isVisible(),'fullscreen opens');
  await page.getByRole('button',{name:'Следующая →',exact:true}).click();
  assert(await page.locator('#modal-position').textContent()==='2 / 10','gallery advances');
  await page.keyboard.press('Escape');assert(!(await page.locator('#poster-modal').isVisible()),'Escape closes');
  await page.getByRole('button',{name:'Повторить блок 1',exact:true}).click();
  const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('quran-hifz:v1')));
  assert(stored.ayahs['96:1'].reads===1&&stored.ayahs['96:2'].reads===1,'block counts independent ayahs');
  assert(!stored.ayahs['96:1'].learned,'count never auto-verifies');
  const first=page.locator('.image-card[data-card="0"]');
  await first.getByRole('button',{name:'✓ Проверено',exact:true}).click();
  assert((await page.locator('#memory-total').textContent()).startsWith('0 /'),'recall gate');
  await first.getByRole('checkbox').check();
  await first.getByRole('button',{name:'✓ Проверено',exact:true}).click();
  assert((await page.locator('#memory-total').textContent()).startsWith('2 /'),'verified block enters fund');
  await page.reload();await page.locator('.image-card').first().waitFor();
  assert((await page.locator('#memory-total').textContent()).startsWith('2 /'),'progress survives reload');
  await page.getByRole('checkbox',{name:'Читать наизусть',exact:true}).check();
  assert(await page.locator('#card-grid .arabic[aria-hidden="true"]').count()===19,'recall hides all ayahs');
  await page.getByRole('checkbox',{name:'Читать наизусть',exact:true}).uncheck();
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no mobile overflow');
  await page.screenshot({path:'output/playwright/alaq-mobile.png'});
  await first.scrollIntoViewIfNeeded();
  await page.screenshot({path:'output/playwright/alaq-card-mobile.png'});
  await page.context().setOffline(true);await page.reload();
  await page.locator('.image-card').first().waitFor();
  assert(await page.locator('.verse').count()===19,'offline all19');
  await page.context().setOffline(false);
  await page.getByRole('link',{name:'Тренажёр хифза',exact:true}).click();
  await page.getByRole('link',{name:'Визуальные карточки Аль-Аляк ↗',exact:true}).waitFor();
  assert((await page.locator('#verified-status').textContent()).includes('Проверено'),'same verified progress in main reader');
  assert(await page.locator('#read-count').textContent()==='1','same counter in main reader');
  assert(errors.length===0,errors.join('; '));
  return 'PASS: 19 exact ayahs, 10 cards/5 rows, gallery, memory gate, shared counters/fund, reload, mobile, offline, main-reader link.';
}
